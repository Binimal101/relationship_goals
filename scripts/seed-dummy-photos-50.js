import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
import { createClient } from '@supabase/supabase-js';
import yaml from 'js-yaml';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const MANIFEST_PATH = path.join(__dirname, 'dummy-photos-50-manifest.json');
const CONFIG_PATH = path.join(__dirname, '..', 'config.yaml');

const SUPABASE_URL = process.env.SUPABASE_URL || process.env.VITE_SUPABASE_URL || 'https://rsilsqauaawyolqrrxmm.supabase.co';
const SUPABASE_KEY =
  process.env.SUPABASE_SERVICE_ROLE_KEY ||
  process.env.SUPABASE_ANON ||
  process.env.VITE_SUPABASE_ANON_KEY ||
  'sb_publishable_e_nq-ALYHeTkkipEVKxW1A_orI_MlSe';
const BATCH_MARKER = '__DUMMY_PHOTO_BATCH_50_V1__';
const BATCH_SIZE = 50;

const supabase = createClient(SUPABASE_URL, SUPABASE_KEY);

function getCredentials() {
  const fromEnv = {
    email: process.env.SUPABASE_EMAIL,
    password: process.env.SUPABASE_PASSWORD,
  };
  if (fromEnv.email && fromEnv.password) return fromEnv;

  if (!fs.existsSync(CONFIG_PATH)) return null;
  const raw = fs.readFileSync(CONFIG_PATH, 'utf8');
  const cfg = yaml.load(raw);
  const email = cfg?.email;
  const password = cfg?.password;
  if (email && password) return { email, password };
  return null;
}

function buildRows() {
  const start = new Date('2025-01-01T00:00:00Z');
  return Array.from({ length: BATCH_SIZE }, (_, idx) => {
    const i = idx + 1;
    const d = new Date(start);
    d.setUTCDate(start.getUTCDate() + idx);
    const isoDate = d.toISOString().slice(0, 10);

    return {
      title: `Dummy Photo ${i}`,
      date: isoDate,
      location: `Dummy Location ${i}`,
      description: `Autogenerated dummy row ${i} (${BATCH_MARKER})`,
      favorite: i % 7 === 0,
      storage_path: null,
      lat: null,
      lng: null,
    };
  });
}

(async () => {
  try {
    if (fs.existsSync(MANIFEST_PATH)) {
      console.error('Refusing to seed: manifest already exists at', MANIFEST_PATH);
      console.error('Run `npm run db:dummy-photos:remove` first to remove the existing batch.');
      process.exit(1);
    }

    const credentials = getCredentials();
    if (credentials && !process.env.SUPABASE_SERVICE_ROLE_KEY) {
      const { error: signInError } = await supabase.auth.signInWithPassword(credentials);
      if (signInError) throw signInError;
      console.log('Authenticated as admin user for RLS-protected insert.');
    }

    const rows = buildRows();
    const { data, error } = await supabase.from('photos').insert(rows).select('id,title,description');
    if (error) throw error;

    if (!Array.isArray(data) || data.length !== BATCH_SIZE) {
      throw new Error(`Expected ${BATCH_SIZE} inserted rows, got ${Array.isArray(data) ? data.length : 0}`);
    }

    const ids = data.map((r) => r.id).filter((id) => Number.isInteger(id));
    if (ids.length !== BATCH_SIZE) {
      throw new Error(`Expected ${BATCH_SIZE} integer ids, got ${ids.length}`);
    }

    const manifest = {
      marker: BATCH_MARKER,
      batchSize: BATCH_SIZE,
      createdAt: new Date().toISOString(),
      ids,
    };

    fs.writeFileSync(MANIFEST_PATH, JSON.stringify(manifest, null, 2), 'utf8');

    console.log(`Seeded ${BATCH_SIZE} dummy photos.`);
    console.log('Manifest written to:', MANIFEST_PATH);
  } catch (err) {
    console.error('Failed to seed dummy photos:', err);
    process.exit(1);
  }
})();
